import '../src/style.css';
import {DataLayer,CommandManager,seed,type TextModel} from '../src/model';
import {RendererManager} from '../src/renderer-manager';
const results=document.querySelector('#results')!,lines:string[]=[];
const assert=(condition:unknown,name:string)=>{if(!condition)throw new Error(name);lines.push('PASS '+name);};
const originalCapture=HTMLElement.prototype.setPointerCapture;
try{
  const data=new DataLayer(seed()),commands=new CommandManager(),manager=new RendererManager(data,commands);
  manager.init();manager.switchView('note');
  const nav=document.querySelector<HTMLElement>('.note-outline')!,line=nav.querySelector<HTMLElement>('.tree-insertion-line')!;
  const row=(id:string)=>nav.querySelector<HTMLElement>(`[data-tree-node="${id}"]`)!;
  const send=(target:HTMLElement,type:string,x:number,y:number)=>target.dispatchEvent(new PointerEvent(type,{bubbles:true,cancelable:true,isPrimary:true,pointerId:5,pointerType:'mouse',button:0,clientX:x,clientY:y}));
  HTMLElement.prototype.setPointerCapture=()=>{};
  const start=(id:string)=>{const r=row(id).getBoundingClientRect();send(row(id),'pointerdown',r.left+60,r.top+r.height/2);};
  const hover=(id:string,fraction:number)=>{const r=row(id).getBoundingClientRect();send(nav,'pointermove',r.left+60,r.top+r.height*fraction);};
  const drop=()=>send(nav,'pointerup',0,0);
  const before=JSON.stringify(data.all());
  start('c');hover('b',.1);
  assert(!line.hidden,'valid sibling drop shows blue insertion line');
  const observer=new MutationObserver(()=>{});observer.observe(nav,{subtree:true,childList:true});
  for(let i=0;i<200;i++)hover('b',.1);
  assert(observer.takeRecords().length===0,'200 drag frames allocate no DOM nodes');observer.disconnect();
  assert(JSON.stringify(data.all())===before,'drag preview does not change models');
  drop();manager.update();
  assert(line.hidden&&nav.querySelector('.tree-insertion-line')===line,'drop reuses and hides insertion line');
  assert([...nav.querySelectorAll<HTMLElement>('[data-tree-node]')].map(el=>el.dataset.treeNode).join(',')==='a,c,b','tree follows updated index');
  assert([...document.querySelectorAll<HTMLElement>('.note-panel')].map(el=>el.dataset.note).join(',')==='a,c,b','current child panels follow updated index');
  assert(!data.getModelByID('ac')&&data.all().some(m=>m.type==='connection'&&m.from==='a'&&m.to==='c'),'drop replaces incoming connection');
  commands.undo();manager.update();assert((data.getModelByID('c') as TextModel).index===1&&!!data.getModelByID('ac'),'one undo restores order and connections');
  start('c');hover('b',.5);drop();manager.update();
  assert(row('c').dataset.parent==='b'&&row('c').dataset.depth==='2','center drop reparents as child');
  commands.undo();manager.update();
  start('a');hover('b',.5);assert(line.hidden,'descendant cannot be chosen as parent');drop();assert(commands.undoStack.length===0,'invalid drop does not create history');
  start('c');hover('b',.1);window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));assert(line.hidden&&commands.undoStack.length===0,'Escape cancels drag');
  manager.setAccess('viewer',{uid:'viewer',email:'viewer@gmail.com',name:'Viewer'});manager.update();start('c');hover('b',.1);assert(line.hidden&&commands.undoStack.length===0,'viewers cannot drag hierarchy');drop();
  manager.setAccess('owner',{uid:'owner',email:'owner@gmail.com',name:'Owner'});manager.update();
  const add=document.querySelector<HTMLButtonElement>('[data-note-add-child]')!;
  assert(!add.hidden,'owner sees add-child button below panels');
  add.click();manager.update();
  const added=data.all().find(m=>m.type==='text'&&!['a','b','c'].includes(m.id)) as TextModel;
  assert(added?.index===2&&data.all().some(m=>m.type==='connection'&&m.from==='a'&&m.to===added.id),'plus creates current child at last index');
  assert(document.querySelector('.note-panel:last-of-type')?.getAttribute('data-note')===added.id,'new child appears last');
  commands.undo();manager.update();assert(!data.getModelByID(added.id),'one undo removes child and connection');
  manager.setAccess('viewer',{uid:'viewer',email:'viewer@gmail.com',name:'Viewer'});manager.update();
  assert(add.hidden,'viewer has no add-child button');add.click();assert(!data.getModelByID(added.id)&&data.all().filter(m=>m.type==='text').length===3,'viewer cannot add child');
  manager.setAccess('owner',{uid:'owner',email:'owner@gmail.com',name:'Owner'});manager.update();
  results.textContent=lines.join('\n')+'\nALL PASSED';
}catch(error){results.textContent=lines.join('\n')+'\nFAIL '+String(error);}
finally{HTMLElement.prototype.setPointerCapture=originalCapture;}
